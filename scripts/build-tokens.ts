/*
 * Builds every token file from tokens/tokens.json (through scripts/lib/tokens.ts), measures contrast and colour
 * vision, and writes the plain-HTML kit.
 *
 *   node scripts/build-tokens.ts           write the files
 *   node scripts/build-tokens.ts --check   write nothing; fail if a file is out of date or a WCAG pair fails
 *
 * Outputs:
 *   packages/design/css/tokens.css        CSS custom properties, light + dark
 *   packages/design/src/tokens.ts         the same values (and the measurements) for TypeScript
 *   packages/design/tailwind/preset.css   Tailwind v4 theme (CSS-first preset)
 *   packages/design/tailwind/preset.js    Tailwind JS preset (for @config, or Tailwind 3)
 *   tokens/report.json                    contrast (WCAG 2.2 + APCA) and colour-vision measurements
 *   DESIGN.md, docs/colour.md, docs/math.md   the tables between <!-- gen:name --> markers
 *   html/kcc.css, html/kcc-charts.js, html/starter.html   the single-file kit
 */
