/** Sample price series: a seeded random walk (Mulberry32), so every build draws the same chart. */
const samplePrice = (() => {
  let a = 7;
  const r = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const pts = [{ x: 0, y: 0.1 }];
  for (let i = 1; i < 90; i++) pts.push({ x: i, y: pts[i - 1].y * Math.exp(0.03 * (r() + r() + r() - 1.5) * 2) });
  return pts.map((p) => ({ x: p.x, y: Math.round(p.y * 1e5) / 1e5 }));
})();
